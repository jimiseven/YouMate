package com.youmate.app.download

import android.app.DownloadManager
import android.content.Context
import android.net.Uri
import android.os.Environment

object DownloadHelper {

    /**
     * Sanitizes file names by removing characters invalid on Android / Linux / FAT filesystems.
     */
    fun sanitizeFileName(rawName: String): String {
        return rawName.replace(Regex("[\\\\/:*?\"<>|]"), "_")
            .replace(Regex("\\s+"), " ")
            .trim()
            .take(120) // Keep length reasonable
    }

    /**
     * Returns the appropriate MIME type based on file extension.
     */
    fun getMimeType(extension: String): String {
        return when (extension.lowercase()) {
            "mp4" -> "video/mp4"
            "webm" -> "video/webm"
            "m4a" -> "audio/mp4"
            "opus" -> "audio/opus"
            "ogg" -> "audio/ogg"
            "mp3" -> "audio/mpeg"
            else -> "*/*"
        }
    }

    /**
     * Enqueues a media download into Android's native DownloadManager.
     * Saves file into public Downloads directory (Environment.DIRECTORY_DOWNLOADS).
     * Shows system progress notification and completion banner.
     *
     * @param context Android context
     * @param streamUrl Direct media stream URL
     * @param title Title of the YouTube video
     * @param format File extension (e.g. "mp4", "m4a", "webm")
     * @return downloadId generated by DownloadManager
     */
    fun enqueueDownload(
        context: Context,
        streamUrl: String,
        title: String,
        format: String
    ): Result<Long> {
        return runCatching {
            val safeExtension = format.lowercase().removePrefix(".")
            val safeTitle = sanitizeFileName(title).ifBlank { "YouTube_Media" }
            val fileName = "$safeTitle.$safeExtension"
            val mimeType = getMimeType(safeExtension)

            val downloadManager = context.getSystemService(Context.DOWNLOAD_SERVICE) as? DownloadManager
                ?: throw IllegalStateException("DownloadManager no está disponible en este dispositivo.")

            val request = DownloadManager.Request(Uri.parse(streamUrl)).apply {
                setTitle(fileName)
                setDescription("Descargando $fileName")
                setNotificationVisibility(DownloadManager.Request.VISIBILITY_VISIBLE_NOTIFY_COMPLETED)
                setDestinationInExternalPublicDir(Environment.DIRECTORY_DOWNLOADS, fileName)
                setAllowedOverMetered(true)
                setAllowedOverRoaming(true)
                setMimeType(mimeType)
            }

            val downloadId = downloadManager.enqueue(request)
            downloadId
        }
    }
}
